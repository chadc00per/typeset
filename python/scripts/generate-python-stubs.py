#!/usr/bin/env python3
"""Write python/chadc00per_typeset/__init__.pyi from data/catalog.json: one class per
semantic type with its value base (str, int, float, tuple or dict), so editors
and type checkers see Email as a str and Money as a dict.
Usage: python3 python/scripts/generate-python-stubs.py   (python/tests checks it is current)"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'python/chadc00per_typeset/__init__.pyi'

# The extra methods some types carry, by type (python/chadc00per_typeset/_types/<name>.py `methods`).
METHODS = {
    'tagset': ['def normalize_item(value: Any, path: str = ...) -> str: ...'],
    'scopes': ['def normalize_item(value: Any, path: str = ...) -> str: ...',
               'def level_of(grants: Any, scope: Any) -> Literal["read", "write"] | None: ...'],
    'currency': ['def minor_units() -> dict[str, int | None]: ...'],
    'money': ['def to_minor(value: Any, path: str = ...) -> MinorUnits: ...',
              'def from_minor(value: Any, path: str = ...) -> MoneyValue: ...'],
}


def base(t):
    storage = t['storage']
    if storage == 'number':
        return 'int' if t['ui'].get('step') == 1 else 'float'
    return {'string': 'str', 'array': 'tuple[Any, ...]', 'object': 'FrozenDict'}[storage]


def render():
    catalog = json.loads((ROOT / 'data/catalog.json').read_text(encoding='utf-8'))
    by_name = {t['name']: t for t in catalog['types']}
    out = ['# Generated by python/scripts/generate-python-stubs.py from data/catalog.json. Do not edit.',
           'from typing import Any, ClassVar, Generic, Literal, TypedDict, TypeVar, overload',
           '', 'from typing_extensions import NotRequired', '',
           'from ._registry import Catalog, FrozenDict, Value, extend as extend, type_of as type_of',
           'from ._lib.errors import ValidationError as ValidationError',
           'from ._struct import Struct as Struct, struct as struct', '',
           "_V = TypeVar('_V')", '',
           'class Issue(TypedDict):', '    path: str', '    message: str',
           "    code: Literal['required', 'invalid', 'range', 'canonical', 'unknown']", '',
           'class CheckOk(TypedDict, Generic[_V]):', '    ok: Literal[True]', '    value: _V', '',
           'class CheckFailed(TypedDict):', '    ok: Literal[False]', '    issues: list[Issue]', '',
           'class TypeUi(TypedDict):', '    control: str', '    options: NotRequired[list[str]]', '    step: NotRequired[int]', '',
           'class TypeMetadata(TypedDict):', '    name: str', '    label: str', '    noun: str', '    description: str', '    example: str',
           '    aliases: list[str]', '    storage: str', '    wire: str', '    collation: str', '    constraints: str', '    ui: TypeUi', '',
           'class MoneyValue(TypedDict):', '    amount: str', '    currency: str', '',
           'class MinorUnits(TypedDict):', '    minor: str', '    currency: str', '',
           "__version__: str", 'types: Catalog', 'names: tuple[str, ...]', 'all: tuple[str, ...]',
           'aliases: dict[str, str]', 'def get(name: str) -> type[Value] | None: ...',
           '@overload', 'def describe(name: None = ...) -> list[TypeMetadata]: ...',
           '@overload', 'def describe(name: str) -> TypeMetadata | None: ...',
           'def to_json_schema(name: str | type[Value] | Struct) -> dict[str, Any] | None: ...', '',
           'class _Type(Value):',
           '    name: ClassVar[str]', '    label: ClassVar[str]', '    noun: ClassVar[str]', '    description: ClassVar[str]',
           '    example: ClassVar[str]', '    aliases: ClassVar[tuple[str, ...]]', '    storage: ClassVar[str]',
           '    wire: ClassVar[str]', '    collation: ClassVar[str]', '    constraints: ClassVar[str]',
           '    ui: ClassVar[FrozenDict]',
           '    @staticmethod', '    def is_(value: Any) -> bool: ...',
           '    @staticmethod', '    def validate(value: Any, path: str | None = ...) -> None: ...',
           '    @staticmethod', '    def describe() -> TypeMetadata: ...',
           '    @staticmethod', '    def to_json_schema() -> dict[str, Any]: ...', '']
    plain = {'str': 'str', 'int': 'int', 'float': 'float', 'tuple[Any, ...]': 'list[Any]', 'FrozenDict': 'dict[str, Any]'}
    special = {'money': 'MoneyValue'}
    for name, class_name in catalog['constructors'].items():
        b = base(by_name[name])
        out.append(f'class {class_name}(_Type, {b}):')
        doc = f'{by_name[name]["description"]}. Example: {by_name[name]["example"]}'
        out.append(f'    {json.dumps(doc, ensure_ascii=False)}')
        out.append(f'    def __new__(cls, value: Any) -> {class_name}: ...')
        out.append('    @staticmethod')
        value = special.get(name, plain[b])
        out.append(f'    def normalize(value: Any, path: str | None = ...) -> {value}: ...')
        out.append('    @staticmethod')
        out.append(f'    def check(value: Any, path: str = ...) -> CheckOk[{value}] | CheckFailed: ...')
        out.append(f'    def value_of(self) -> {value}: ...')
        for method in METHODS.get(name, []):
            out += ['    @staticmethod', f'    {method}']
        out.append('')
    return '\n'.join(out)


if __name__ == '__main__':
    OUT.write_text(render(), encoding='utf-8', newline='\n')
    print(f'{OUT.relative_to(ROOT)} written')
