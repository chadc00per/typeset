#!/usr/bin/env node
// Bundles src/lib/code.js with the parsers it uses (acorn, parse5, css-tree,
// saxes, @lezer/python, at the versions package.json pins) into
// python/chadc00per_typeset/_parsers.js: a classic script defining
// globalThis.typesetParsers, which the Python package runs in an embedded V8
// (lib/code.py), so both packages check code with the same code. Their license
// texts go beside it in _parsers.LICENSES.txt.
//   node js/scripts/generate-python-parsers.js           write both files
//   node js/scripts/generate-python-parsers.js --check   fail if either is stale (js/tests/parsers.test.js)
import { build } from 'esbuild';
import { bundledPackages, licenseNotice } from './licenses.js';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.join(import.meta.dirname, '../..');
const OUT = path.join(ROOT, 'python/chadc00per_typeset/_parsers.js');
const LICENSES = path.join(ROOT, 'python/chadc00per_typeset/_parsers.LICENSES.txt');

// #vendor as code.js needs it: the parsers only (vendor.js would also pull in libphonenumber).
const vendor = {
  name: 'parsers-only-vendor',
  setup(b) {
    b.onResolve({ filter: /^#vendor$/ }, () => ({ path: 'vendor', namespace: 'parsers' }));
    b.onLoad({ filter: /.*/, namespace: 'parsers' }, () => ({
      resolveDir: ROOT,
      contents: `import { parser as lezerPython } from '@lezer/python';
import * as acorn from 'acorn';
import parseCss from 'css-tree/parser';
import * as parse5 from 'parse5';
import * as saxes from 'saxes';
export const javascriptParser = () => acorn;
export const htmlParser = () => parse5;
export const cssParser = () => parseCss;
export const xmlParser = () => saxes;
export const pythonParser = () => lezerPython;`
    }));
  }
};

const result = await build({
  stdin: { contents: "import { parses } from './js/src/lib/code.js';\nglobalThis.typesetParsers = parses;\n", resolveDir: ROOT, sourcefile: 'parsers-entry.js' },
  bundle: true,
  format: 'iife',
  platform: 'neutral',
  mainFields: ['module', 'main'],
  target: 'es2022',
  minify: true,
  legalComments: 'none',
  charset: 'utf8',
  metafile: true,
  write: false,
  plugins: [vendor],
  banner: { js: '/* Generated by scripts/generate-python-parsers.js from src/lib/code.js; do not edit. Bundled licenses: _parsers.LICENSES.txt */' },
  logLevel: 'warning'
});

const packages = bundledPackages(result.metafile);
const licenses = packages.map(licenseNotice);
const outputs = {
  [OUT]: result.outputFiles[0].text,
  [LICENSES]: 'Third-party code bundled into _parsers.js.\n\n' + licenses.join('\n')
};

if (process.argv.includes('--check')) {
  const stale = Object.entries(outputs).filter(([file, text]) => !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text);
  if (stale.length) {
    console.error(`stale: ${stale.map(([file]) => path.relative(ROOT, file)).join(', ')}; run npm run parsers`);
    process.exit(1);
  }
} else {
  for (const [file, text] of Object.entries(outputs)) fs.writeFileSync(file, text);
  console.log(`${path.relative(ROOT, OUT)}: ${(outputs[OUT].length / 1024).toFixed(0)} kB from ${packages.join(', ')}`);
}
