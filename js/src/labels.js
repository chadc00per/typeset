// A label as a noun: words lowercased except acronyms and words with inner
// capitals (URL, UPC-A, JavaScript, WebVTT), with a "(…)" or "[…]" note dropped:
// "Postal Code" → "postal code", "IP Range (CIDR)" → "IP range".
export function nounFromLabel(label) {
  return label.replace(/\s*[([].*$/, '').replace(/[A-Za-z][A-Za-z0-9]*/g, word =>
    (word === word.toUpperCase() || /[A-Z].*[A-Z]/.test(word) ? word : word.toLowerCase()));
}

